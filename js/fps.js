  // Billboard sprites (badges + guards + the hacking terminal) via the
  // inverse camera matrix, sorted back-to-front, occluded by the wall
  // zBuffer.
  function drawSprites() {
    const sprites = [];
    badges.forEach((b) => { if (!b.collected) sprites.push({ x: b.x, y: b.y, type: "badge" }); });
    guards.forEach((g) => sprites.push({ x: g.x, y: g.y, type: "guard", g }));
    barrels.forEach((b) => { if (!b.exploded || b.flashT > 0) sprites.push({ x: b.x, y: b.y, type: "barrel", b }); });
    if (currentTerminal) sprites.push({ x: currentTerminal.x, y: currentTerminal.y, type: "terminal" });
    pickups.forEach((pk) => { if (!pk.collected) sprites.push({ x: pk.x, y: pk.y, type: "pickup", pk }); });

    sprites.sort((a, b) => {
      const da = (a.x - posX) ** 2 + (a.y - posY) ** 2;
      const db = (b.x - posX) ** 2 + (b.y - posY) ** 2;
      return db - da;
    });

    const invDet = 1 / (planeX * dirY - dirX * planeY);
    const trophyImg = window.SPRITES && window.SPRITES.platformTiles;
    const guardImg = window.SPRITES && window.SPRITES.daveGuard;
    const sentinelImg = window.SPRITES && window.SPRITES.sentinelGuard;

    sprites.forEach((sp) => {
      const spriteX = sp.x - posX;
      const spriteY = sp.y - posY;
      const transformX = invDet * (dirY * spriteX - dirX * spriteY);
      const transformY = invDet * (-planeY * spriteX + planeX * spriteY);
      if (transformY <= 0.15) return;

      const screenX = Math.floor((VIEW_W / 2) * (1 + transformX / transformY));
      const spriteSize = sp.type === "guard" ? (sp.g.isBoss ? 1.3 : 0.9)
        : sp.type === "terminal" ? 0.7
        : sp.type === "pickup" ? 0.36
        : sp.type === "barrel" ? (sp.b.flashT > 0 ? 1.6 : 0.62)
        : 0.42;
      const spriteHeight = Math.abs(Math.floor((VIEW_H / transformY) * spriteSize));
      const spriteWidth = sp.type === "terminal" ? spriteHeight * (160 / 224) : spriteHeight;

      const drawStartY = Math.floor(-spriteHeight / 2 + VIEW_H / 2 + (sp.type === "guard" ? VIEW_H * 0.06 : sp.type === "terminal" ? VIEW_H * 0.02 : 0));
      const drawStartX = Math.floor(screenX - spriteWidth / 2);

      const col0 = Math.max(0, Math.floor(drawStartX / STRIP_W));
      const col1 = Math.min(RAY_COLS - 1, Math.floor((drawStartX + spriteWidth) / STRIP_W));
      let anyVisible = false;
      for (let c = col0; c <= col1; c++) {
        if (transformY < zBuffer[c]) { anyVisible = true; break; }
      }
      if (!anyVisible) return;

      ctx.save();
      const region = new Path2D();
      for (let c = col0; c <= col1; c++) {
        if (transformY < zBuffer[c]) {
          region.rect(c * STRIP_W, 0, STRIP_W + 0.5, VIEW_H);
        }
      }
      ctx.clip(region);
      ctx.imageSmoothingEnabled = false;

      if (sp.type === "badge" && trophyImg && trophyImg.complete && trophyImg.naturalWidth > 0) {
        ctx.drawImage(
          trophyImg, TROPHY_SRC.x, TROPHY_SRC.y, TROPHY_SRC.w, TROPHY_SRC.h,
          drawStartX, drawStartY, spriteWidth, spriteHeight
        );
      } else if (sp.type === "badge") {
        ctx.fillStyle = "#FACC15";
        ctx.beginPath();
        ctx.arc(screenX, drawStartY + spriteHeight / 2, spriteWidth / 2.4, 0, Math.PI * 2);
        ctx.fill();
      } else if (sp.type === "terminal" && IMG_TERMINAL.complete && IMG_TERMINAL.naturalWidth > 0) {
        if (currentTerminal && currentTerminal.hacked) ctx.filter = "hue-rotate(60deg) saturate(1.3)";
        ctx.drawImage(IMG_TERMINAL, drawStartX, drawStartY, spriteWidth, spriteHeight);
        ctx.filter = "none";
      } else if (sp.type === "guard" && sp.g.isBoss && sentinelImg && sentinelImg.complete && sentinelImg.naturalWidth > 0) {
        // The Sentinel gets its own dedicated sprite (see
        // tools/gen_villain_boss_sprite.py) instead of the ordinary
        // guard art with a color filter, same "the boss looks like a
        // distinct character" treatment as Story Mode's Boss.draw().
        const frameW = sentinelImg.naturalWidth / 2;
        const frameH = sentinelImg.naturalHeight;
        const frame = Math.floor(sp.g.animPhase) % 2;
        if (sp.g.defeated) ctx.filter = "grayscale(1) brightness(0.6)";
        else if (sp.g.paralyzed > 0) ctx.filter = "grayscale(1) brightness(0.75)";
        ctx.drawImage(
          sentinelImg, frame * frameW, 0, frameW, frameH,
          drawStartX, drawStartY, spriteWidth, spriteHeight
        );
        ctx.filter = "none";
      } else if (sp.type === "guard" && guardImg && guardImg.complete && guardImg.naturalWidth > 0) {
        const frameW = guardImg.naturalWidth / 2;
        const frameH = guardImg.naturalHeight;
        const frame = Math.floor(sp.g.animPhase) % 2;
        if (sp.g.defeated) ctx.filter = "grayscale(1) brightness(0.6)";
        else if (sp.g.paralyzed > 0) ctx.filter = "grayscale(1) brightness(0.75)";
        else if (sp.g.isBoss) ctx.filter = "hue-rotate(320deg) saturate(1.6) brightness(1.05)";
        ctx.drawImage(
          guardImg, frame * frameW, 0, frameW, frameH,
          drawStartX, drawStartY, spriteWidth, spriteHeight
        );
        ctx.filter = "none";
      } else if (sp.type === "barrel") {
        // A live barrel reads as a hazard-striped drum; a detonating one
        // is a brief expanding orange flash at the same world position.
        const bx = screenX;
        const byTop = drawStartY;
        if (sp.b.flashT > 0) {
          const f = sp.b.flashT / 0.45;
          ctx.globalAlpha = f;
          const grad = ctx.createRadialGradient(bx, byTop + spriteHeight / 2, 0, bx, byTop + spriteHeight / 2, spriteWidth / 2);
          grad.addColorStop(0, "#FEF3C7");
          grad.addColorStop(0.45, "#F97316");
          grad.addColorStop(1, "rgba(239,68,68,0)");
          ctx.fillStyle = grad;
          ctx.beginPath();
          ctx.arc(bx, byTop + spriteHeight / 2, spriteWidth / 2, 0, Math.PI * 2);
          ctx.fill();
          ctx.globalAlpha = 1;
        } else {
          const bw = spriteWidth * 0.62;
          ctx.fillStyle = "#B45309";
          ctx.strokeStyle = "#FBBF24";
          ctx.lineWidth = Math.max(1, spriteWidth * 0.05);
          ctx.fillRect(bx - bw / 2, byTop, bw, spriteHeight);
          ctx.strokeRect(bx - bw / 2, byTop, bw, spriteHeight);
          // Two hazard bands so it's unmistakably an explosive drum.
          ctx.fillStyle = "#FBBF24";
          [0.28, 0.62].forEach((t) => ctx.fillRect(bx - bw / 2, byTop + spriteHeight * t, bw, spriteHeight * 0.1));
        }
      } else if (sp.type === "pickup") {
        const color = sp.pk.type === "keycard" ? "#F59E0B" : sp.pk.type === "health" ? "#22C55E" : "#38BDF8";
        const icon = sp.pk.type === "keycard" ? "🔑" : sp.pk.type === "health" ? "✚" : "⚡";
        ctx.fillStyle = "#0F172A";
        ctx.strokeStyle = color;
        ctx.lineWidth = 2;
        ctx.shadowColor = color;
        ctx.shadowBlur = 8;
        ctx.beginPath();
        ctx.arc(screenX, drawStartY + spriteHeight / 2, spriteWidth / 2.2, 0, Math.PI * 2);
        ctx.fill();
        ctx.stroke();
        ctx.shadowBlur = 0;
        ctx.fillStyle = color;
        ctx.font = `bold ${Math.round(spriteHeight * 0.5)}px 'Share Tech Mono', monospace`;
        ctx.textAlign = "center";
        ctx.textBaseline = "middle";
        ctx.fillText(icon, screenX, drawStartY + spriteHeight / 2 + 1);
      } else {
        ctx.fillStyle = sp.g && sp.g.paralyzed > 0 ? "#64748B" : "#EF4444";
        ctx.fillRect(drawStartX, drawStartY, spriteWidth, spriteHeight);
      }
      ctx.restore();
    });
  }

