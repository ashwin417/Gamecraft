  /* ---------------- FpsGuard: lightweight 2D patrol/chase/paralyze ---------------- */
  class FpsGuard {
    constructor(x, y, waypoints, speed) {
      this.x = x;
      this.y = y;
      this.waypoints = waypoints;
      this.wpIndex = 0;
      this.speed = speed || 1.5;
      this.chaseSpeed = this.speed * 1.55;
      this.paralyzed = 0;
      this.alert = false;
      this.sightRange = 7.0;
      // Detection is a forward-facing cone, not omniscient — a guard
      // patrolling east-west won't spot a player approaching from
      // directly behind it. closeRadius is a small point-blank exception.
      this.facingAngle = Math.PI;
      this.sightHalfFov = Math.PI / 4;
      this.closeRadius = 1.3;
      this.animPhase = 0;
    }

    hasLineOfSight(tx, ty) {
      const dx = tx - this.x;
      const dy = ty - this.y;
      const dist = Math.hypot(dx, dy);
      if (dist > this.sightRange) return false;
      const steps = Math.ceil(dist * 4);
      for (let i = 1; i < steps; i++) {
        const t = i / steps;
        if (isWall(this.x + dx * t, this.y + dy * t)) return false;
      }
      return true;
    }

    canDetect(px, py) {
      const dx = px - this.x;
      const dy = py - this.y;
      const dist = Math.hypot(dx, dy);
      if (dist > this.sightRange) return false;
      if (!this.hasLineOfSight(px, py)) return false;
      if (dist <= this.closeRadius) return true;
      const angleToTarget = Math.atan2(dy, dx);
      let diff = angleToTarget - this.facingAngle;
      while (diff > Math.PI) diff -= Math.PI * 2;
      while (diff < -Math.PI) diff += Math.PI * 2;
      return Math.abs(diff) <= this.sightHalfFov;
    }

    update(dt, playerX, playerY) {
      if (this.paralyzed > 0) {
        this.paralyzed = Math.max(0, this.paralyzed - dt);
        return;
      }

      const canSeePlayer = this.canDetect(playerX, playerY);
      if (canSeePlayer) this.alert = true;

      let tx, ty, speed;
      if (this.alert && canSeePlayer) {
        tx = playerX; ty = playerY; speed = this.chaseSpeed;
      } else {
        const wp = this.waypoints[this.wpIndex];
        tx = wp.x; ty = wp.y; speed = this.speed;
        if (Math.hypot(tx - this.x, ty - this.y) < 0.15) {
          this.wpIndex = (this.wpIndex + 1) % this.waypoints.length;
        }
      }

      const dx = tx - this.x;
      const dy = ty - this.y;
      const dist = Math.hypot(dx, dy);
      if (dist > 0.02) {
        this.facingAngle = Math.atan2(dy, dx);
        this.animPhase += dt * speed * 3;
        const stepX = (dx / dist) * speed * dt;
        const stepY = (dy / dist) * speed * dt;
        if (!isWall(this.x + stepX, this.y)) this.x += stepX;
        if (!isWall(this.x, this.y + stepY)) this.y += stepY;
      }
    }

    paralyze(duration) {
      this.paralyzed = duration;
    }
  }

  /* ---------------- FpsSniper: the Datacenter archetype's cover-shooter threat ----
     A stationary enemy that never chases. When it has line of sight to
     the player it paints a laser sight and holds the lock for
     SNIPER_LOCK_TIME; if the lock survives to the end, it fires for real
     damage. BREAKING LINE OF SIGHT CANCELS THE LOCK — that single rule is
     what turns the datacenter floors into cover-shooter rooms, because the
     server racks placed in buildFloorLayout() are exactly the thing that
     breaks it. A stun shot paralyzes it like any guard, which also drops
     the lock. It has a full 360° awareness on purpose (it's scanning, not
     patrolling), so the counter is cover, never approaching from behind. */
  class FpsSniper extends FpsGuard {
    constructor(x, y, angle) {
      // Waypoints are its own position — it never moves, but the base
      // class's update() still expects a non-empty waypoint list.
      super(x, y, [{ x, y }], 0);
      this.isSniper = true;
      this.facingAngle = angle || 0;
      this.sightRange = SNIPER_RANGE;
      this.sightHalfFov = Math.PI;  // scans all directions
      this.lockT = 0;               // seconds of uninterrupted lock so far
      this.cooldownT = 0;
      this.firedFlash = 0;          // brief visual after a shot lands
      this.hasLock = false;
    }

    /** Returns true on the frame it actually fires, so the caller can
     *  apply damage (update() has no access to player health directly). */
    updateSniper(dt, playerX, playerY) {
      if (this.firedFlash > 0) this.firedFlash = Math.max(0, this.firedFlash - dt);
      if (this.paralyzed > 0) {
        this.paralyzed = Math.max(0, this.paralyzed - dt);
        this.lockT = 0;
        this.hasLock = false;
        return false;
      }
      if (this.cooldownT > 0) this.cooldownT = Math.max(0, this.cooldownT - dt);

      const sees = this.hasLineOfSight(playerX, playerY);
      this.hasLock = sees && this.cooldownT <= 0;
      if (!this.hasLock) {
        // Cover broke the lock (or it's reloading) — the charge resets
        // completely rather than pausing, so ducking behind a rack is a
        // real reset and not just a delay.
        this.lockT = 0;
        return false;
      }
      this.alert = true;
      this.facingAngle = Math.atan2(playerY - this.y, playerX - this.x);
      this.lockT += dt;
      if (this.lockT >= SNIPER_LOCK_TIME) {
        this.lockT = 0;
        this.cooldownT = SNIPER_COOLDOWN;
        this.firedFlash = 0.25;
        return true;
      }
      return false;
    }

    /** How far through its lock it is, 0..1 — drives the laser sight's
     *  brightness/thickness so the player can read how long they have. */
    get lockRatio() {
      return Math.max(0, Math.min(1, this.lockT / SNIPER_LOCK_TIME));
    }

    // Never moves; the base update() would try to walk it to its own
    // position and recompute facing, which would fight updateSniper().
    update() { /* intentionally inert — see updateSniper() */ }
  }

  /* ---------------- FpsBoss: Floor 10's exit guardian ---------------- */
  // Reuses all of FpsGuard's patrol/chase/detect/paralyze plumbing — the
  // only real differences: it takes `maxHits` separate paralyze() hits
  // before it's actually defeated (the first hits still apply a normal
  // temporary freeze, same window-of-opportunity a stun hit gives against
  // an ordinary guard), it doesn't move once defeated, and it's kept out
  // of the `guards` array entirely until activateFinalBoss() wakes it —
  // see update()'s badge-collection check — so it can't be touched, seen,
  // or chased into before that.
  class FpsBoss extends FpsGuard {
    constructor(x, y, waypoints, speed, opts) {
      super(x, y, waypoints, speed);
      opts = opts || {};
      this.isBoss = true;
      this.name = opts.name || "The Sentinel";
      this.maxHits = opts.maxHits || 3;
      this.hitsTaken = 0;
      this.defeated = false;
      this.sightRange = 9.0;
      this.sightHalfFov = Math.PI / 2.1;
      this.chaseSpeed = speed * 1.8;
      this.awake = false; // flips true in update()'s badge-collection check — see activateFinalBoss note there
    }

    paralyze(duration) {
      if (this.defeated) return;
      this.hitsTaken++;
      if (this.hitsTaken >= this.maxHits) {
        this.defeated = true;
        this.paralyzed = 0;
        this.alert = false;
      } else {
        super.paralyze(duration);
      }
    }

    update(dt, playerX, playerY) {
      if (this.defeated) return;
      super.update(dt, playerX, playerY);
    }
  }

