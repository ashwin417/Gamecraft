  function handleTerminalGuess(i) {
    if (i === currentTerminal.qa.correct) {
      currentTerminal.hacked = true;
      stunCharges = Math.min(STUN_CHARGES_CAP, stunCharges + 1);
      updateHud();
      window.CG.audio.playCollect();
      closeTerminalPuzzle();
    } else {
      window.CG.audio.playHit();
      const fb = document.getElementById("fpsTerminalFeedback");
      if (fb) fb.textContent = "Access denied — that command trips the audit log. Try another.";
    }
  }

