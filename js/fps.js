  function drawMinimap() {
    const w = mmCanvas.width, h = mmCanvas.height;
    mmCtx.clearRect(0, 0, w, h);
    const scale = Math.min(w / currentW, h / currentH);
    mmCtx.fillStyle = "rgba(2,6,23,0.4)";
    mmCtx.fillRect(0, 0, w, h);
    for (let r = 0; r < currentH; r++) {
      for (let c = 0; c < currentW; c++) {
        const val = currentGrid[r][c];
        if (val === 0) continue;
        if (val === 3) {
          const anim = doorAnimAt(c, r);
          mmCtx.fillStyle = anim >= 0.92 ? "rgba(161,98,7,0.35)" : "#A16207";
        } else if (val === LOCKED_DOOR) {
          mmCtx.fillStyle = "#DC2626"; // still-locked door — reads as a hazard, not a normal one
        } else {
          mmCtx.fillStyle = val === 2 ? "#F59E0B" : currentTint;
        }
        mmCtx.fillRect(c * scale, r * scale, scale, scale);
      }
    }
    badges.forEach((b) => {
      if (b.collected) return;
      mmCtx.fillStyle = "#FACC15";
      mmCtx.beginPath();
      mmCtx.arc(b.x * scale, b.y * scale, Math.max(1.5, scale * 0.25), 0, Math.PI * 2);
      mmCtx.fill();
    });
    if (currentTerminal && !currentTerminal.hacked) {
      mmCtx.fillStyle = "#22C55E";
      mmCtx.fillRect(currentTerminal.x * scale - 2, currentTerminal.y * scale - 2, 4, 4);
    }
    pickups.forEach((pk) => {
      if (pk.collected) return;
      mmCtx.fillStyle = pk.type === "keycard" ? "#F59E0B" : pk.type === "health" ? "#22C55E" : "#38BDF8";
      mmCtx.beginPath();
      mmCtx.arc(pk.x * scale, pk.y * scale, Math.max(1.5, scale * 0.22), 0, Math.PI * 2);
      mmCtx.fill();
    });
    guards.forEach((g) => {
      mmCtx.fillStyle = g.paralyzed > 0 ? "#64748B" : "#EF4444";
      mmCtx.beginPath();
      mmCtx.arc(g.x * scale, g.y * scale, Math.max(1.5, scale * 0.3), 0, Math.PI * 2);
      mmCtx.fill();
    });

    mmCtx.save();
    mmCtx.translate(posX * scale, posY * scale);
    mmCtx.rotate(angle);
    mmCtx.fillStyle = "#22C55E";
    mmCtx.beginPath();
    mmCtx.moveTo(6, 0);
    mmCtx.lineTo(-4, 4);
    mmCtx.lineTo(-4, -4);
    mmCtx.closePath();
    mmCtx.fill();
    mmCtx.restore();
  }

