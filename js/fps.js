  function escapeHtmlLocal(str) {
    const div = document.createElement("div");
    div.textContent = str;
    return div.innerHTML;
  }

  /** Rooftop archetype: drops a wave of attackers at the arena's spawn
   *  points. Wave size grows every wave, and each wave is slightly faster
   *  than the last, so holding out gets genuinely harder rather than just
   *  longer. Spawn points are room centers (guaranteed open floor), and
   *  any point too close to the player is skipped so a wave can never
   *  materialize on top of them. */
  function spawnWave() {
    if (!holdout) return;
    holdout.wave++;
    const count = WAVE_ENEMY_BASE + Math.floor(holdout.wave / 2);
    const speed = holdout.enemySpeed * (1 + 0.08 * (holdout.wave - 1));
    let placed = 0;
    for (let i = 0; i < count; i++) {
      const sp = holdout.spawnPoints[(holdout.wave + i) % holdout.spawnPoints.length];
      if (Math.hypot(sp.x - posX, sp.y - posY) < 3.5) continue;
      const g = new FpsGuard(sp.x, sp.y, [
        { x: sp.x, y: sp.y },
        { x: posX, y: posY },
      ], speed);
      g.isWaveEnemy = true;
      g.alert = true; // they know exactly where you are — that's the point
      g.sightRange = 20;
      g.sightHalfFov = Math.PI;
      guards.push(g);
      placed++;
    }
    if (placed) window.CG.audio.playWarning();
  }

  /** Rooftop archetype: a barrel detonates when a stun shot connects with
   *  it (see tryFireStun()). The blast permanently defeats every guard in
   *  BARREL_RADIUS — the only thing in FPS Mode that removes an enemy for
   *  good rather than freezing it — and hurts the player too if they're
   *  inside the radius, which is what stops "stand next to a barrel and
   *  shoot it" from being the whole strategy. */
  function detonateBarrel(barrel) {
    if (barrel.exploded) return;
    barrel.exploded = true;
    barrel.flashT = 0.45;
    window.CG.audio.playHit();

    guards.forEach((g) => {
      if (g.defeated) return;
      if (Math.hypot(g.x - barrel.x, g.y - barrel.y) <= BARREL_RADIUS) {
        if (g.isBoss) {
          // The Sentinel isn't one-shot by a barrel — it still takes its
          // normal multi-hit path, so the finale can't be trivialized.
          g.paralyze(STUN_DURATION);
        } else {
          g.defeated = true;
          g.paralyzed = 999;
        }
      }
    });

    // Chain reaction: a barrel in the blast goes up too.
    barrels.forEach((b) => {
      if (!b.exploded && Math.hypot(b.x - barrel.x, b.y - barrel.y) <= BARREL_RADIUS) detonateBarrel(b);
    });

    if (Math.hypot(posX - barrel.x, posY - barrel.y) <= BARREL_RADIUS) {
      playerHealth = Math.max(0, playerHealth - BARREL_PLAYER_DAMAGE);
      hurtFlashTime = 0.5;
      updateHud();
      if (playerHealth <= 0) failMission();
    }
  }

  function updateBarrels(dt) {
    barrels.forEach((b) => { if (b.flashT > 0) b.flashT = Math.max(0, b.flashT - dt); });
  }

  function advanceFloor() {
    if (floorIndex + 1 >= TOTAL_FLOORS) {
      winMission();
      return;
    }
    window.CG.audio.playCheckpoint();
    floorIndex++;
    state = "loading";
    ensureImagesThenBuild(floorIndex, () => { state = "playing"; });
  }

  function failMission() {
    state = "gameover";
    window.FpsModeActive = false;
    if (document.pointerLockElement) document.exitPointerLock();
    window.CG.audio.playGameOver();
    endRun(false, "Too many hits and the alarm trips. Mission over.");
  }

  function winMission() {
    state = "victory";
    window.FpsModeActive = false;
    if (document.pointerLockElement) document.exitPointerLock();
    window.CG.audio.playServerSecured();
    endRun(true, "All 10 floors breached. Every badge accounted for, every elevator cleared.");
  }

  function endRun(won, reasonText) {
    const elapsedSec = Math.max(0, Math.round((performance.now() - startTime) / 1000));
    const name = window.CG.getPlayerName();
    const floorsCleared = won ? TOTAL_FLOORS : floorIndex;
    renderResult({ won, reasonText, name, elapsedSec, floorsCleared });
    UI.showScreen("screen-fps-result");
  }

  function formatTime(totalSec) {
    const m = Math.floor(totalSec / 60).toString().padStart(2, "0");
    const s = (totalSec % 60).toString().padStart(2, "0");
    return `${m}:${s}`;
  }

  function renderResult(data) {
    const set = (id, text) => { const n = document.getElementById(id); if (n) n.textContent = text; };
    const titleEl = document.getElementById("fpsResultTitle");
    const eyebrowEl = document.getElementById("fpsResultEyebrow");
    if (titleEl) titleEl.textContent = data.won ? "TOWER CLEARED" : "SECURITY ALERT";
    if (eyebrowEl) eyebrowEl.textContent = data.won ? "Mission Debrief" : "Mission Failed";
    set("fpsResultPlayerName", data.name);
    set("fpsResultReason", data.reasonText);
    set("fpsResultFloors", `${data.floorsCleared}/${TOTAL_FLOORS}`);
    set("fpsResultBadges", `${badgesCollected}/${badges.length}`);
    set("fpsResultTime", formatTime(data.elapsedSec));

    const card = document.querySelector("#screen-fps-result .card");
    if (card) card.classList.toggle("result-victory", !!data.won);
  }

  /* ---------------- Rendering ---------------- */
  function render() {
    ctx.fillStyle = "#0b1220";
    ctx.fillRect(0, 0, VIEW_W, VIEW_H / 2);

    renderFloorCast();

    for (let col = 0; col < RAY_COLS; col++) {
      const cameraX = (2 * col) / RAY_COLS - 1;
      const rayDirX = dirX + planeX * cameraX;
      const rayDirY = dirY + planeY * cameraX;

      let mapX = Math.floor(posX);
      let mapY = Math.floor(posY);

      const deltaDistX = rayDirX === 0 ? 1e30 : Math.abs(1 / rayDirX);
      const deltaDistY = rayDirY === 0 ? 1e30 : Math.abs(1 / rayDirY);

      let stepX, stepY, sideDistX, sideDistY;
      if (rayDirX < 0) { stepX = -1; sideDistX = (posX - mapX) * deltaDistX; }
      else { stepX = 1; sideDistX = (mapX + 1 - posX) * deltaDistX; }
      if (rayDirY < 0) { stepY = -1; sideDistY = (posY - mapY) * deltaDistY; }
      else { stepY = 1; sideDistY = (mapY + 1 - posY) * deltaDistY; }

      let hit = 0, side = 0, wallType = 1, doorAnim = 0, depth = 0;
      while (hit === 0 && depth < MAX_DEPTH * 2) {
        if (sideDistX < sideDistY) {
          sideDistX += deltaDistX; mapX += stepX; side = 0;
        } else {
          sideDistY += deltaDistY; mapY += stepY; side = 1;
        }
        depth++;
        if (mapX < 0 || mapX >= currentW || mapY < 0 || mapY >= currentH) { hit = 1; wallType = 1; break; }
        const cellVal = currentGrid[mapY][mapX];
        if (cellVal === 0) continue;
        if (cellVal === 3) {
          const anim = doorAnimAt(mapX, mapY);
          if (anim >= 0.92) continue; // fully open — the ray passes straight through
          hit = 1; wallType = 3; doorAnim = anim;
        } else {
          hit = 1; wallType = cellVal;
        }
      }

      const perpWallDist = side === 0
        ? Math.max(0.0001, sideDistX - deltaDistX)
        : Math.max(0.0001, sideDistY - deltaDistY);
      zBuffer[col] = perpWallDist;

      const lineHeight = Math.floor(VIEW_H / perpWallDist);
      const drawStart = Math.max(0, -lineHeight / 2 + VIEW_H / 2);
      const drawEnd = Math.min(VIEW_H, lineHeight / 2 + VIEW_H / 2);

      // Exact wall-hit position, for the texture's horizontal coordinate.
      let wallX = side === 0 ? posY + perpWallDist * rayDirY : posX + perpWallDist * rayDirX;
      wallX -= Math.floor(wallX);
      // A still-locked door (wallType 4, see LOCKED_DOOR) reuses the
      // hazard texture — it should read as "off-limits," not "a door you
      // just haven't opened yet" — until the floor's keycard converts its
      // grid cell to an ordinary door (see the "keycard" pickup handler).
      const texSrc = (wallType === 2 || wallType === 4) ? (side === 0 ? hazardTexLight : hazardTexDark)
        : wallType === 3 ? (side === 0 ? doorTexLight : doorTexDark)
        : (side === 0 ? wallTexLight : wallTexDark);
      const texW = texSrc.width, texH = texSrc.height;
      let texX = Math.floor(wallX * texW);
      if (side === 0 && rayDirX > 0) texX = texW - texX - 1;
      if (side === 1 && rayDirY < 0) texX = texW - texX - 1;
      // A door mid-slide shows a shifted texture window — a cheap but
      // effective "sliding open" read within this column-based renderer.
      if (wallType === 3 && doorAnim > 0) texX = (texX + Math.floor(doorAnim * texW)) % texW;
      texX = Math.max(0, Math.min(texW - 1, texX));

      const fog = Math.min(0.72, perpWallDist / MAX_DEPTH);
      ctx.drawImage(texSrc, texX, 0, 1, texH, col * STRIP_W, drawStart, STRIP_W + 0.5, drawEnd - drawStart);
      if (fog > 0.02) {
        ctx.fillStyle = `rgba(15,23,42,${fog})`;
        ctx.fillRect(col * STRIP_W, drawStart, STRIP_W + 0.5, drawEnd - drawStart);
      }
    }

    drawExitGlow();
    drawSprites();
    if (stunFlashTime > 0) {
      ctx.fillStyle = `rgba(56,189,248,${(stunFlashTime / 0.15) * 0.25})`;
      ctx.fillRect(0, 0, VIEW_W, VIEW_H);
    }
    if (hurtFlashTime > 0) {
      ctx.fillStyle = `rgba(239,68,68,${(hurtFlashTime / 0.35) * 0.35})`;
      ctx.fillRect(0, 0, VIEW_W, VIEW_H);
    }

    drawSniperWarning();
    drawWeaponView();
    drawInteractPrompt();
    drawMouseLookHint();
    drawBossBanner();
    drawHoldoutBanner();
    drawMinimap();
  }

  /** Datacenter archetype: a full-screen warning while a sniper holds a
   *  lock on the player. Drawn in screen space (not as a world sprite)
   *  because the whole point is that it's readable even when the sniper
   *  itself is a distant speck — the player needs to know to get behind a
   *  rack NOW, and how long they have. Escalates as the lock completes. */
  function drawSniperWarning() {
    const locking = snipers.filter((s) => s.hasLock && s.paralyzed <= 0);
    if (!locking.length) return;
    const worst = locking.reduce((a, b) => (a.lockRatio > b.lockRatio ? a : b));
    const r = worst.lockRatio;

    // Red vignette that tightens as the shot charges.
    ctx.save();
    const grad = ctx.createRadialGradient(VIEW_W / 2, VIEW_H / 2, VIEW_H * (0.55 - r * 0.2), VIEW_W / 2, VIEW_H / 2, VIEW_H * 0.95);
    grad.addColorStop(0, "rgba(239,68,68,0)");
    grad.addColorStop(1, `rgba(239,68,68,${0.16 + r * 0.34})`);
    ctx.fillStyle = grad;
    ctx.fillRect(0, 0, VIEW_W, VIEW_H);

    ctx.textAlign = "center";
    ctx.font = "bold 15px 'Share Tech Mono', monospace";
    ctx.fillStyle = "#EF4444";
    ctx.shadowColor = "#EF4444";
    ctx.shadowBlur = 10;
    // Top of the view, not the bottom: the first-person weapon sprite
    // (drawWeaponView) owns the bottom-center third of the screen and
    // was clipping this warning in half — exactly the moment the player
    // most needs to read it. Datacenter floors carry neither the boss
    // banner nor the extraction banner, so this band is free there.
    ctx.fillText("⊕ SNIPER LOCK — BREAK LINE OF SIGHT", VIEW_W / 2, 100);

    // Lock progress bar.
    const barW = 220, barH = 7;
    const barX = VIEW_W / 2 - barW / 2, barY = 110;
    ctx.shadowBlur = 0;
    ctx.fillStyle = "rgba(2,6,23,0.85)";
    ctx.fillRect(barX - 2, barY - 2, barW + 4, barH + 4);
    ctx.fillStyle = "#EF4444";
    ctx.fillRect(barX, barY, barW * r, barH);
    ctx.restore();
  }

  /** Rooftop archetype: the extraction countdown and current wave. */
  function drawHoldoutBanner() {
    if (!holdout) return;
    ctx.save();
    ctx.textAlign = "center";
    if (holdout.complete) {
      ctx.font = "bold 15px 'Share Tech Mono', monospace";
      ctx.fillStyle = "#22C55E";
      ctx.shadowColor = "#22C55E";
      ctx.shadowBlur = 10;
      ctx.fillText("✔ EXTRACTION READY — GET TO THE ELEVATOR", VIEW_W / 2, 52);
    } else {
      const secs = Math.ceil(holdout.timeLeft);
      const urgent = secs <= 10;
      ctx.font = "bold 16px 'Share Tech Mono', monospace";
      ctx.fillStyle = urgent ? "#FACC15" : "#38BDF8";
      ctx.shadowColor = ctx.fillStyle;
      ctx.shadowBlur = 10;
      ctx.fillText(`⏱ EXTRACTION IN ${secs}s  ·  WAVE ${holdout.wave}`, VIEW_W / 2, 52);
      ctx.shadowBlur = 0;
      const barW = 260, barH = 6;
      const barX = VIEW_W / 2 - barW / 2, barY = 60;
      const done = 1 - holdout.timeLeft / holdout.total;
      ctx.fillStyle = "rgba(2,6,23,0.85)";
      ctx.fillRect(barX - 2, barY - 2, barW + 4, barH + 4);
      ctx.fillStyle = urgent ? "#FACC15" : "#38BDF8";
      ctx.fillRect(barX, barY, barW * done, barH);
    }
    ctx.restore();
  }

  /** Classic per-pixel floor-casting (Lodev-style): for each screen row
   *  below the horizon, computes the world-space floor position at both
   *  screen edges and steps across, sampling a tiled/checkerboarded
   *  texture per pixel. Computed at RAY_COLS horizontal resolution and
   *  every other row (then duplicated) to keep this affordable — the
   *  low-res tile pattern reads fine at that density and it keeps this a
   *  cheap per-frame cost rather than a full 900x300 pixel loop. */
  function renderFloorCast() {
    const bufW = RAY_COLS;
    const bufH = VIEW_H / 2;
    const imgData = ctx.createImageData(bufW, bufH);
    const out = imgData.data;
    const rayDirX0 = dirX - planeX, rayDirY0 = dirY - planeY;
    const rayDirX1 = dirX + planeX, rayDirY1 = dirY + planeY;
    const posZ = 0.5 * VIEW_H;

    for (let y = 0; y < bufH; y += FLOOR_ROW_STEP) {
      const p = y + 1; // avoid divide-by-zero right at the horizon
      const rowDistance = posZ / p;
      const floorStepX = (rowDistance * (rayDirX1 - rayDirX0)) / bufW;
      const floorStepY = (rowDistance * (rayDirY1 - rayDirY0)) / bufW;
      let floorX = posX + rowDistance * rayDirX0;
      let floorY = posY + rowDistance * rayDirY0;
      const fog = Math.min(0.75, rowDistance / MAX_DEPTH);
      const fogInv = 1 - fog;

      for (let x = 0; x < bufW; x++) {
        const cellX = Math.floor(floorX), cellY = Math.floor(floorY);
        let tx = Math.floor((floorX - cellX) * FLOOR_TEX_SIZE) & (FLOOR_TEX_SIZE - 1);
        let ty = Math.floor((floorY - cellY) * FLOOR_TEX_SIZE) & (FLOOR_TEX_SIZE - 1);
        const parity = (((cellX % 2) + 2) % 2) ^ (((cellY % 2) + 2) % 2);
        const texData = parity ? floorTexDarkData : floorTexLightData;
        const ti = (ty * FLOOR_TEX_SIZE + tx) * 4;

        const r = texData[ti] * fogInv + 15 * fog;
        const g = texData[ti + 1] * fogInv + 23 * fog;
        const b = texData[ti + 2] * fogInv + 42 * fog;

        const oi = (y * bufW + x) * 4;
        out[oi] = r; out[oi + 1] = g; out[oi + 2] = b; out[oi + 3] = 255;
        if (FLOOR_ROW_STEP > 1 && y + 1 < bufH) {
          const oi2 = ((y + 1) * bufW + x) * 4;
          out[oi2] = r; out[oi2 + 1] = g; out[oi2 + 2] = b; out[oi2 + 3] = 255;
        }

        floorX += floorStepX;
        floorY += floorStepY;
      }
    }

    // Blit the low-res floor buffer up to full canvas resolution, blocky
    // (no smoothing) to match the flat-shaded/chunky aesthetic.
    const off = renderFloorCast._off || (renderFloorCast._off = document.createElement("canvas"));
    off.width = bufW; off.height = bufH;
    off.getContext("2d").putImageData(imgData, 0, 0);
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(off, 0, 0, bufW, bufH, 0, VIEW_H / 2, VIEW_W, VIEW_H / 2);
  }

