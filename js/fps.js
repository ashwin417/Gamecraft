  /* ---------------- Loop ---------------- */
  function loop(now) {
    const dt = Math.min(0.05, (now - lastTime) / 1000);
    lastTime = now;

    if (state === "playing") {
      update(dt);
      render();
    }

    if (state === "playing") rafId = requestAnimationFrame(loop);
  }

  function update(dt) {
    const input = window.CG.input;

    // Turning: mouse-look (pointerlockchange/mousemove above) drives angle
    // directly whenever the pointer is locked, so Left/Right are freed up
    // to strafe instead. Falls back to keyboard-only turning otherwise.
    if (pointerLocked) {
      let strafe = 0;
      if (input.left) strafe -= 1;
      if (input.right) strafe += 1;
      if (strafe !== 0) {
        const strafeX = -dirY * strafe * MOVE_SPEED * dt;
        const strafeY = dirX * strafe * MOVE_SPEED * dt;
        tryMove(strafeX, strafeY);
        bobPhase += dt * 9;
      }
    } else {
      if (input.left) angle -= TURN_SPEED * dt;
      if (input.right) angle += TURN_SPEED * dt;
      if (angle > Math.PI) angle -= Math.PI * 2;
      if (angle < -Math.PI) angle += Math.PI * 2;
    }
    updateDirPlane();

    let moveDir = 0;
    if (input.up) moveDir += 1;
    if (input.down) moveDir -= 1;
    if (moveDir !== 0) {
      const stepX = dirX * moveDir * MOVE_SPEED * dt;
      const stepY = dirY * moveDir * MOVE_SPEED * dt;
      tryMove(stepX, stepY);
      bobPhase += dt * 9;
    }

    if (input.fire) {
      input.fire = false;
      tryFireStun();
    }

    if (input.interact) {
      input.interact = false;
      tryInteract();
      if (state !== "playing") return;
    }

    if (stunFlashTime > 0) stunFlashTime = Math.max(0, stunFlashTime - dt);
    if (gunFireTime > 0) gunFireTime = Math.max(0, gunFireTime - dt);
    if (hurtCooldownT > 0) hurtCooldownT = Math.max(0, hurtCooldownT - dt);
    if (hurtFlashTime > 0) hurtFlashTime = Math.max(0, hurtFlashTime - dt);

    updateDoors(dt);
    guards.forEach((g) => g.update(dt, posX, posY));

    // ---- Datacenter archetype: sniper lock-on ----
    // Runs after ordinary guard movement so a sniper's line-of-sight test
    // sees this frame's real world state. A fired shot applies damage
    // immediately, bypassing hurtCooldownT (that window exists to stop
    // melee contact from melting the bar frame-by-frame; a sniper already
    // rate-limits itself with SNIPER_COOLDOWN).
    for (const s of snipers) {
      if (s.updateSniper(dt, posX, posY)) {
        playerHealth = Math.max(0, playerHealth - SNIPER_DAMAGE);
        hurtFlashTime = 0.4;
        window.CG.audio.playHit();
        updateHud();
        if (playerHealth <= 0) { failMission(); return; }
      }
    }

    // ---- Rooftop archetype: extraction hold-out + waves ----
    if (holdout && !holdout.complete) {
      holdout.timeLeft = Math.max(0, holdout.timeLeft - dt);
      holdout.waveTimer -= dt;
      if (holdout.waveTimer <= 0) {
        holdout.waveTimer = holdout.waveInterval;
        spawnWave();
      }
      if (holdout.timeLeft <= 0) {
        holdout.complete = true;
        window.CG.audio.playCheckpoint();
        updateHud();
      }
    }
    if (barrels.length) updateBarrels(dt);

    // A guard's touch now costs health instead of ending the run outright
    // — HURT_INVULN gives a brief breather after each hit so standing in
    // a guard's path for a couple of frames doesn't melt the player
    // instantly. A defeated boss (see FpsBoss) is permanently safe, same
    // as a paralyzed guard; `g.defeated` is simply undefined (falsy) on
    // every ordinary guard, so this is a no-op check for those.
    if (hurtCooldownT <= 0) {
      for (const g of guards) {
        if (g.paralyzed <= 0 && !g.defeated && Math.hypot(g.x - posX, g.y - posY) < TOUCH_RADIUS) {
          playerHealth = Math.max(0, playerHealth - DAMAGE_PER_HIT);
          hurtCooldownT = HURT_INVULN;
          hurtFlashTime = 0.35;
          window.CG.audio.playHit();
          updateHud();
          if (playerHealth <= 0) { failMission(); return; }
          break;
        }
      }
    }

    badges.forEach((b) => {
      if (!b.collected && Math.hypot(b.x - posX, b.y - posY) < 0.4) {
        b.collected = true;
        badgesCollected++;
        window.CG.audio.playCollect();
        updateHud();
      }
    });

    pickups.forEach((pk) => {
      if (pk.collected || Math.hypot(pk.x - posX, pk.y - posY) >= PICKUP_RADIUS) return;
      pk.collected = true;
      if (pk.type === "keycard") {
        hasKeycard = true;
        // Converts the locked cell into an ordinary auto-open door — its
        // doorStates entry already exists (every doorCell, locked or not,
        // gets one in buildLevel()), so it immediately behaves exactly
        // like any other door the moment the player walks up to it.
        if (currentLockedDoorCell) {
          const [lc, lr] = currentLockedDoorCell;
          currentGrid[lr][lc] = 3;
        }
      } else if (pk.type === "ammo") {
        stunCharges = Math.min(STUN_CHARGES_CAP, stunCharges + AMMO_PICKUP_GAIN);
      } else if (pk.type === "health") {
        playerHealth = Math.min(PLAYER_MAX_HEALTH, playerHealth + HEALTH_PICKUP_GAIN);
      }
      window.CG.audio.playCollect();
      updateHud();
    });

    // The final floor's Sentinel wakes the instant every badge is in —
    // same "dormant until the real objective is done" shape as Story
    // Mode's Floor 5 boss — and from then on blocks the win until defeated.
    if (currentBoss && !currentBoss.awake && badgesCollected >= badges.length) {
      currentBoss.awake = true;
      guards.push(currentBoss);
      window.CG.audio.playCheckpoint();
    }

    const col = Math.floor(posX);
    const row = Math.floor(posY);
    const bossClear = !currentBoss || currentBoss.defeated;
    // On a rooftop floor the extraction timer is an additional gate on top
    // of badges and the boss: the exit is sealed until the hold-out ends,
    // which is what makes those floors a survival objective rather than a
    // faster version of "find everything and leave".
    const holdoutClear = !holdout || holdout.complete;
    if (badgesCollected >= badges.length && bossClear && holdoutClear && isExitCell(col, row)) {
      advanceFloor();
    }
  }

  /** Doors slide open for any mover (the player, or a guard mid-chase)
   *  standing near their center, and auto-close a short delay after the
   *  last one leaves — classic Wolfenstein-3D door behavior. Only the
   *  player's proximity is checked (guards in this layout patrol within a
   *  single room and never approach a door on their own patrol route; a
   *  chasing guard can still walk through one the player opened, since
   *  isWall() consults the same live anim value). */
  function updateDoors(dt) {
    doorStates.forEach((d, key) => {
      const [r, c] = key.split(",").map(Number);
      const cx = c + 0.5, cy = r + 0.5;
      const dist = Math.hypot(posX - cx, posY - cy);
      if (dist < DOOR_OPEN_RADIUS) {
        d.open = true;
        d.closeTimer = DOOR_AUTO_CLOSE_DELAY;
      } else if (d.open) {
        d.closeTimer -= dt;
        if (d.closeTimer <= 0) d.open = false;
      }
      const target = d.open ? 1 : 0;
      const step = DOOR_ANIM_SPEED * dt;
      if (d.anim < target) d.anim = Math.min(target, d.anim + step);
      else if (d.anim > target) d.anim = Math.max(target, d.anim - step);
    });
  }

  function tryMove(stepX, stepY) {
    const nx = posX + stepX;
    const ny = posY + stepY;
    if (!isWall(nx + Math.sign(stepX) * COLLIDE_RADIUS, posY) && !isWall(nx - Math.sign(stepX) * COLLIDE_RADIUS, posY)) {
      posX = nx;
    }
    if (!isWall(posX, ny + Math.sign(stepY) * COLLIDE_RADIUS) && !isWall(posX, ny - Math.sign(stepY) * COLLIDE_RADIUS)) {
      posY = ny;
    }
  }

  function tryFireStun() {
    if (stunCharges <= 0) return;
    let target = null;
    let bestDist = Infinity;
    for (const g of guards) {
      if (g.defeated) continue; // a defeated boss (see FpsBoss) is a spent target
      const dx = g.x - posX;
      const dy = g.y - posY;
      const dist = Math.hypot(dx, dy);
      if (dist > STUN_RANGE) continue;
      const targetAngle = Math.atan2(dy, dx);
      let diff = targetAngle - angle;
      while (diff > Math.PI) diff -= Math.PI * 2;
      while (diff < -Math.PI) diff += Math.PI * 2;
      if (Math.abs(diff) > STUN_FOV) continue;
      if (!g.hasLineOfSight(posX, posY)) continue;
      if (dist < bestDist) { bestDist = dist; target = g; }
    }

    // A live barrel in the same cone, NEARER than the best guard target,
    // is what the shot actually hits — so on rooftop floors the player can
    // deliberately aim past an enemy at the barrel behind it. Checked
    // after guard targeting so the comparison is against a real distance.
    let barrelTarget = null;
    let barrelDist = Infinity;
    for (const b of barrels) {
      if (b.exploded) continue;
      const dx = b.x - posX, dy = b.y - posY;
      const dist = Math.hypot(dx, dy);
      if (dist > STUN_RANGE) continue;
      let diff = Math.atan2(dy, dx) - angle;
      while (diff > Math.PI) diff -= Math.PI * 2;
      while (diff < -Math.PI) diff += Math.PI * 2;
      if (Math.abs(diff) > STUN_FOV) continue;
      if (dist < barrelDist) { barrelDist = dist; barrelTarget = b; }
    }

    gunFireTime = 0.18;
    window.CG.audio.playHit();

    if (barrelTarget && barrelDist <= bestDist) {
      stunCharges--;
      stunFlashTime = 0.15;
      detonateBarrel(barrelTarget);
      updateHud();
      return;
    }

    if (!target) return;

    stunCharges--;
    target.paralyze(STUN_DURATION);
    stunFlashTime = 0.15;
    updateHud();
  }

  /** Opens the current floor's hacking-terminal mini-puzzle if the player
   *  is close enough and it hasn't already been solved. No-ops otherwise
   *  (walking up and pressing E away from the terminal is silently
   *  ignored — this is an optional side objective, never a required gate,
   *  on every floor). */
  function tryInteract() {
    if (!currentTerminal || currentTerminal.hacked) return;
    const dist = Math.hypot(currentTerminal.x - posX, currentTerminal.y - posY);
    if (dist > INTERACT_RADIUS) return;
    openTerminalPuzzle();
  }

